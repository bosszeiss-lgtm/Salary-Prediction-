import streamlit as st
import pandas as pd
import numpy as np
import joblit

model = joblit.load("Salary_Prediction_model.pkl")
encoder = joblit.load("Label_Encoder.pkl")


st.title("Salary Prediction")

age = st.number_input("Age",18,65)
gender = st.selectbox("Gender",encoder["Gender"].classes_)
education_level = st.selectbox("Education Level",encoder["Education Level"].classes_)
job_title = st.selectbox("Job Title",encoder["Job Title"].classes_)
years_of_experience = st.number_input("Years of Experience",0,40)

df = pd.DataFrame({
    "Age":[age],
    "Gender":["gender"],
    "Education Level":["education_level"],
    "Job Title":["job_title"],
    "Years of Experience":[years_of_experience]
})

if st.button("Predict Salary"):
  for col in encoder:
    df[col] = encoder[col].transform(df[col])

prediction = model.predict(df)
st.success(f"Predicted Salary: {prediction[0]:,.2f}")
